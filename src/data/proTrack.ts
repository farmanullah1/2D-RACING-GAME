const grid = mapStr.map(row => row.split('').map(char => charMap[char] ?? TileType.Grass));

const waypoints: Vector2D[] = [];

// Waypoints MUST go in the direction of the Start line.
// Start line is at row 11, col 7-10.
// We decided it goes UP here. So -Math.PI/2.
// Let's trace it backwards from the start line and then reverse, or just trace it forward.
// Start line is at {x: 8.5, y: 11} going UP.

// 1. Up the left straight
for(let r=11; r>=7; r--) waypoints.push({x: 8.5*TILE_SIZE, y: (r + 0.5)*TILE_SIZE});

// 2. Top left curve
waypoints.push({x: 9*TILE_SIZE, y: 6.5*TILE_SIZE});
waypoints.push({x: 10*TILE_SIZE, y: 5.5*TILE_SIZE});

// 3. Top straight (moving right)
for(let c=11; c<=30; c++) waypoints.push({x: (c + 0.5)*TILE_SIZE, y: 5.5*TILE_SIZE});

// 4. Top right curve
waypoints.push({x: 32*TILE_SIZE, y: 6*TILE_SIZE});
waypoints.push({x: 33.5*TILE_SIZE, y: 7.5*TILE_SIZE});

// 5. Right straight (moving down)
for(let r=9; r<=34; r++) waypoints.push({x: 33.5*TILE_SIZE, y: (r + 0.5)*TILE_SIZE});

// 6. Bottom right curve
waypoints.push({x: 33.5*TILE_SIZE, y: 36.5*TILE_SIZE});
waypoints.push({x: 32*TILE_SIZE, y: 37.5*TILE_SIZE});

// 7. Bottom straight (moving left)
for(let c=30; c>=13; c--) waypoints.push({x: (c + 0.5)*TILE_SIZE, y: 37.5*TILE_SIZE});

// 8. Bottom left curve
waypoints.push({x: 11.5*TILE_SIZE, y: 37*TILE_SIZE});
waypoints.push({x: 10.5*TILE_SIZE, y: 35.5*TILE_SIZE});

// 9. Lower left straight (moving up)
for(let r=34; r>=29; r--) waypoints.push({x: 10.5*TILE_SIZE, y: (r + 0.5)*TILE_SIZE});

// 10. Chicane (moving up-left)
waypoints.push({x: 10*TILE_SIZE, y: 27*TILE_SIZE});
waypoints.push({x: 9.5*TILE_SIZE, y: 26.5*TILE_SIZE});
waypoints.push({x: 9*TILE_SIZE, y: 25.5*TILE_SIZE});
waypoints.push({x: 8.5*TILE_SIZE, y: 24*TILE_SIZE});

// 11. Upper left straight (moving up back to start)
for(let r=22; r>=12; r--) waypoints.push({x: 8.5*TILE_SIZE, y: (r + 0.5)*TILE_SIZE});

