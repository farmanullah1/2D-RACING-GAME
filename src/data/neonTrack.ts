const grid = mapStr.map(row => row.split('').map(char => charMap[char] ?? TileType.Grass));

const waypoints: Vector2D[] = [];

// Neon Centerline path:
// Start is at col 8.5, row 11.5 going UP.
for(let r=11; r>=7; r--) waypoints.push({x: 8.5*TILE_SIZE, y: (r + 0.5)*TILE_SIZE});
waypoints.push({x: 9*TILE_SIZE, y: 6.5*TILE_SIZE});
waypoints.push({x: 10*TILE_SIZE, y: 5.5*TILE_SIZE});

for(let c=11; c<=34; c++) waypoints.push({x: (c + 0.5)*TILE_SIZE, y: 5.5*TILE_SIZE});
waypoints.push({x: 35.5*TILE_SIZE, y: 6.5*TILE_SIZE});
waypoints.push({x: 36.5*TILE_SIZE, y: 8*TILE_SIZE});

for(let r=9; r<=36; r++) waypoints.push({x: 36.5*TILE_SIZE, y: (r + 0.5)*TILE_SIZE});
waypoints.push({x: 35.5*TILE_SIZE, y: 38*TILE_SIZE});
waypoints.push({x: 34*TILE_SIZE, y: 38.5*TILE_SIZE});

for(let c=33; c>=12; c--) waypoints.push({x: (c + 0.5)*TILE_SIZE, y: 38.5*TILE_SIZE});
waypoints.push({x: 10.5*TILE_SIZE, y: 38*TILE_SIZE});
waypoints.push({x: 9.5*TILE_SIZE, y: 36.5*TILE_SIZE});

for(let r=35; r>=12; r--) waypoints.push({x: 8.5*TILE_SIZE, y: (r + 0.5)*TILE_SIZE});

